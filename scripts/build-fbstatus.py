"""Build mibox-fbstatus: the live HDMI status screen for the slim image.

Generates target/fbstatus/fbstatus-font.h from two pinned Terminus console
fonts (Ubuntu console-setup, SIL OFL 1.1), then compiles a static ARM binary
for the box and a native host binary used only for --preview renders.
Run under WSL: python3 scripts/build-fbstatus.py
"""
import gzip
import hashlib
import json
import struct
import subprocess
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
FONTS = {
    'font_big': ('/usr/share/consolefonts/Uni2-TerminusBold32x16.psf.gz',
                 '7923369ee8eac3e9d597f6e8a952ba205963a6354548e6ef2d17850b6781fdff'),
    'font_small': ('/usr/share/consolefonts/Uni2-TerminusBold20x10.psf.gz', None),
}
SOURCE = ROOT / 'src/hardware/mibox-fbstatus.c'
OUT = ROOT / 'target/fbstatus'


def parse_psf(data):
    """Return (width, height, glyph bytes for ASCII 0x20..0x7E)."""
    if data[:4] == b'\x72\xb5\x4a\x86':
        _, header, flags, count, size, height, width = struct.unpack('<7I', data[4:32])
        glyphs = [data[header + i * size: header + (i + 1) * size] for i in range(count)]
        table = data[header + count * size:] if flags & 1 else None
        separator, start = b'\xff', b'\xfe'
    elif data[:2] == b'\x36\x04':
        mode, size = data[2], data[3]
        count = 512 if mode & 1 else 256
        width, height = 8, size
        glyphs = [data[4 + i * size: 4 + (i + 1) * size] for i in range(count)]
        raw = data[4 + count * size:] if mode & 6 else None
        table = None
        if raw is not None:   # PSF1 table is UCS-2; re-encode to the PSF2 shape
            out = bytearray()
            for (value,) in struct.iter_unpack('<H', raw[:len(raw) // 2 * 2]):
                out += b'\xff' if value == 0xFFFF else b'\xfe' if value == 0xFFFE else chr(value).encode()
            table = bytes(out)
        separator, start = b'\xff', b'\xfe'
    else:
        raise ValueError('not a PSF font')
    mapping = {}
    if table is not None:
        for index, entry in enumerate(table.split(separator)[:len(glyphs)]):
            singles = entry.split(start)[0].decode('utf-8', 'replace')
            for char in singles:
                mapping.setdefault(ord(char), index)
    result = []
    for code in range(0x20, 0x7F):
        index = mapping.get(code, code)
        result.append(glyphs[index])
    return width, height, result


def main():
    OUT.mkdir(parents=True, exist_ok=True)
    lines = ['/* Generated by scripts/build-fbstatus.py; Terminus fonts, SIL OFL 1.1. */',
             'struct font { int w, h, stride; const unsigned char *bits; };']
    pins = {}
    for name, (path, expected) in FONTS.items():
        packed = Path(path).read_bytes()
        digest = hashlib.sha256(packed).hexdigest()
        if expected and digest != expected:
            raise ValueError(f'{path} differs from its pin')
        pins[path] = digest
        width, height, glyphs = parse_psf(gzip.decompress(packed))
        stride = (width + 7) // 8
        blob = b''.join(glyphs)
        if len(blob) != 95 * height * stride:
            raise ValueError('glyph size')
        body = ','.join(str(b) for b in blob)
        lines.append(f'static const unsigned char {name}_bits[] = {{{body}}};')
        lines.append(f'static const struct font {name} = {{{width}, {height}, {stride}, {name}_bits}};')
    header = OUT / 'fbstatus-font.h'
    header.write_text('\n'.join(lines) + '\n')
    sysroot = ROOT / 'target/hardware-cross/sysroot/usr/arm-linux-gnueabihf'
    warnings = ['-Os', '-Wall', '-Wextra', '-Werror', '-I', str(OUT)]
    arm = OUT / 'mibox-fbstatus'
    subprocess.run(['arm-linux-gnueabihf-gcc', '--sysroot=' + str(sysroot), '-isystem', str(sysroot / 'include'),
                    '-L' + str(sysroot / 'lib'), '-B' + str(sysroot / 'lib') + '/', '-static', *warnings,
                    '-o', str(arm), str(SOURCE)], check=True)
    subprocess.run(['arm-linux-gnueabihf-strip', str(arm)], check=True)
    elf = subprocess.run(['arm-linux-gnueabihf-readelf', '-h', '-l', str(arm)],
                         capture_output=True, text=True, check=True).stdout
    if 'INTERP' in elf or 'DYNAMIC' in elf or 'Machine:                           ARM' not in elf:
        raise RuntimeError('mibox-fbstatus must be a static ARM ELF')
    host = OUT / 'mibox-fbstatus-host'
    subprocess.run(['gcc', *warnings, '-o', str(host), str(SOURCE)], check=True)

    def sha(path):
        return hashlib.sha256(path.read_bytes()).hexdigest()
    report = dict(source_sha256=sha(SOURCE), font_header_sha256=sha(header), fonts=pins,
                  arm_binary_sha256=sha(arm), arm_bytes=arm.stat().st_size,
                  static_arm_elf=True, physical_validation=False)
    (OUT / 'manifest.json').write_text(json.dumps(report, indent=2) + '\n')
    print(json.dumps(report, indent=2))


if __name__ == '__main__':
    main()
