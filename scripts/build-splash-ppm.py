BG = (0x00, 0x40, 0xFF)
TITLE = (0xFF, 0xB0, 0x00)
TEXT = (0xD0, 0xD8, 0xE0)
ACCENT = (0x40, 0xC0, 0x80)
WIDTH, HEIGHT = 1280, 1080
LINES = [
    ('MIBOX CUSTOM OS', TITLE, 6),
    ('HDMI SPLASH ACTIVE', ACCENT, 3),
    ('SSH ROOT@192.168.1.222', TEXT, 3),
    ('USB ADB 248243005297', TEXT, 3),
    ('SERIAL TTY S0 115200 8N1', TEXT, 3),
]


def glyph(char):
    if char.upper() in FONT:
        return FONT[char.upper()]
    raise ValueError('unsupported glyph: %r' % char)


def draw_text(pixels, text, color, scale, left, top):
    cursor_x = left
    for char in text:
        glyph_rows = glyph(char)
        for row, bits in enumerate(glyph_rows):
            for column in range(8):
                # font8x8: bit 0 is the leftmost pixel.
                if not (bits >> column) & 1:
                    continue
                for sy in range(scale):
                    for sx in range(scale):
                        x = cursor_x + column * scale + sx
                        y = top + row * scale + sy
                        if 0 <= x < WIDTH and 0 <= y < HEIGHT:
                            index = (y * WIDTH + x) * 3
                            pixels[index:index + 3] = bytes(color)
        cursor_x += 9 * scale
    return cursor_x


def main():
    pixels = bytearray(bytes(BG) * (WIDTH * HEIGHT))
    y = 260
    for text, color, scale in LINES:
        draw_text(pixels, text, color, scale, 120, y)
        y += 8 * scale + 8 * scale
    # bottom rule, one accent line
    for x in range(120, WIDTH - 120):
        for sy in range(4):
            index = ((HEIGHT - 160 + sy) * WIDTH + x) * 3
            pixels[index:index + 3] = bytes(ACCENT)
    ppm = b'P6\n1280 1080\n255\n' + bytes(pixels)
    output = Path(__file__).resolve().parents[1] / 'target/splash/mibox-splash.ppm'
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_bytes(ppm)
    report = dict(path=str(output), bytes=len(ppm),
                  width=WIDTH, height=HEIGHT, lines=[line[0] for line in LINES])
    print(json.dumps(report, indent=2))


if __name__ == '__main__':
    main()
